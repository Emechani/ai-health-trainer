SECRET_KEY = os.environ.get('DJANGO_SECRET_KEY', '').strip()
if IS_PRODUCTION:
    if len(SECRET_KEY) < 50 or SECRET_KEY.startswith('django-insecure-') or len(set(SECRET_KEY)) < 5:
        raise ImproperlyConfigured('Production requires a new strong DJANGO_SECRET_KEY (50+ characters)')
elif not SECRET_KEY:
    # 로컬 키는 재시작마다 바뀌지 않도록 별도 Git 제외 파일에 보관합니다.
    secret_file = BASE_DIR / '.django-dev-secret'
    if not secret_file.exists():
        try:
            with secret_file.open('x', encoding='utf-8') as stream:
                stream.write(secrets.token_urlsafe(50))
        except FileExistsError:
            pass
    SECRET_KEY = secret_file.read_text(encoding='utf-8').strip()
    if not SECRET_KEY:
        raise ImproperlyConfigured('Local Django secret file is empty')


